-- The mod's layer rules (Scripts/Modules/categories.lua) applied to what extract.py read from the game: writes
-- data/world.lua (placed things by layer, layers of classes, respawn times) and data/foliage.lua (interactable foliage
-- of the layers that show it). Run by extract.py; Lua so the rules live in one place, shared with the mod.
-- Usage: lua5.4 tools/extract/layers.lua <extracted.lua> <data dir>
-- extracted.lua: return { game = { buildid, utoc_size }, actors = { {class, x, y, z, extra?}, ... },
--                         classes = { [class] = { class, parent, ..., "Object" } }, respawn = { [class] = seconds },
--                         foliage = { mesh, x, y, z, mesh, x, y, z, ... } }

local here = arg[0]:match("^(.*)/tools/extract/") or "."
package.path = here .. "/ResourceMarkers/Scripts/?.lua;" .. package.path
local Categories = require("Modules.categories")

local src, dir = arg[1], arg[2]
assert(src and dir, "usage: layers.lua <extracted.lua> <data dir>")
local data = dofile(src)

-- The game build the data comes from (the mod warns when the installed game is a different one).
local function stamp(game)
    local keys = {}
    for k in pairs(game or {}) do keys[#keys + 1] = k end
    table.sort(keys)
    local parts = {}
    for _, k in ipairs(keys) do parts[#parts + 1] = string.format("%s = %q", k, game[k]) end
    return "{ " .. table.concat(parts, ", ") .. " }"
end

local function sorted_keys(t)
    local keys = {}
    for k in pairs(t) do keys[#keys + 1] = k end
    table.sort(keys)
    return keys
end

-- world.lua ------------------------------------------------------------------------------------------------------
-- Everything placed is kept, also outside the main landmass (vault interiors, other regions): the game's map only
-- draws icons where it has a background for the player's current area.
local classIndex, classList, cats, counts, skipped = {}, {}, {}, {}, {}
for _, a in ipairs(data.actors) do
    local cls, x, y, z, extra = a[1], a[2], a[3], a[4], a[5]
    local category = Categories.classify(cls, data.classes[cls] or { cls }, extra)
    if not category then
        skipped[cls] = (skipped[cls] or 0) + 1
    else
        if not classIndex[cls] then
            classList[#classList + 1] = cls
            classIndex[cls] = #classList
        end
        local list = cats[category.id] or {}
        cats[category.id] = list
        local n = #list
        list[n + 1], list[n + 2], list[n + 3], list[n + 4] = classIndex[cls], math.floor(x + 0.5), math.floor(y + 0.5),
            math.floor(z + 0.5)
        counts[category.id] = (counts[category.id] or 0) + 1
    end
end
-- The layer of every class (also ones only spawned at runtime, e.g. a harvested plant), for saved and live state.
local classCats = {}
for cls, chain in pairs(data.classes) do
    local category = Categories.classify(cls, chain)
    if category then classCats[cls] = category.id end
end

local f = assert(io.open(dir .. "/world.lua", "w"))
f:write("-- Generated by tools/extract from the game's files. Do not edit.\n")
f:write("-- cats[layer] = flat list of class index, x, y, z (game units); classCats[class] = layer;\n")
f:write("-- respawn[class] = seconds of in-game time it takes to come back.\nreturn {\n")
f:write("  game = ", stamp(data.game), ",\n  respawn = {\n")
for _, cls in ipairs(sorted_keys(data.respawn or {})) do
    -- classes with a layer, or placed (vents get their layer from their type, not their class)
    if classCats[cls] or classIndex[cls] then f:write(string.format("    [%q] = %d,\n", cls, data.respawn[cls])) end
end
f:write("  },\n  classes = {\n")
for _, cls in ipairs(classList) do f:write(string.format("    %q,\n", cls)) end
f:write("  },\n  cats = {\n")
for _, category in ipairs(Categories) do
    local list = cats[category.id]
    if list then
        f:write("    ", category.id, " = {")
        for i = 1, #list, 4 do
            if (i - 1) % 64 == 0 then f:write("\n      ") end
            f:write(list[i], ",", list[i + 1], ",", list[i + 2], ",", list[i + 3], ",")
        end
        f:write("\n    },\n")
    end
end
f:write("  },\n  classCats = {\n")
for _, cls in ipairs(sorted_keys(classCats)) do f:write(string.format("    [%q] = %q,\n", cls, classCats[cls])) end
f:write("  },\n}\n")
f:close()

-- foliage.lua ----------------------------------------------------------------------------------------------------
-- Only meshes a layer shows (no branches or loose stones); an instance listed twice (two tiles) is kept once.
local meshes, meshIndex, points, seen = {}, {}, {}, {}
local fol = data.foliage or {}
for i = 1, #fol, 4 do
    local mesh, x, y, z = fol[i], fol[i + 1], fol[i + 2], fol[i + 3]
    if Categories.for_mesh(mesh) then
        local key = mesh .. " " .. math.floor(x / 50) .. " " .. math.floor(y / 50)
        if not seen[key] then
            seen[key] = true
            if not meshIndex[mesh] then
                meshes[#meshes + 1] = mesh
                meshIndex[mesh] = #meshes
            end
            points[#points + 1] = string.format("%d,%d,%d,%d", meshIndex[mesh], x, y, z)
        end
    end
end
f = assert(io.open(dir .. "/foliage.lua", "w"))
f:write("-- Generated by tools/extract from the game's files. Do not edit.\n")
f:write("-- meshes[i] = static mesh name; points = flat list of mesh index, x, y, z (game units, world space).\n")
f:write("return {\n  game = ", stamp(data.game), ",\n  meshes = {\n")
for _, m in ipairs(meshes) do f:write(string.format("    %q,\n", m)) end
f:write("  },\n  points = {\n")
for i = 1, #points, 8 do f:write("    ", table.concat(points, ",", i, math.min(i + 7, #points)), ",\n") end
f:write("  },\n}\n")
f:close()

-- Summary ----------------------------------------------------------------------------------------------------------
local placed, layers = 0, {}
for _, category in ipairs(Categories) do
    if counts[category.id] then
        placed = placed + counts[category.id]
        layers[#layers + 1] = category.id .. " " .. counts[category.id]
    end
end
print(string.format("world.lua: %d placed things in %d layers; foliage.lua: %d instances of %d meshes", placed, #layers,
    #points, #meshes))
local rest = {}
for cls, n in pairs(skipped) do rest[#rest + 1] = { cls, n } end
table.sort(rest, function(a, b) return a[2] > b[2] end)
local top = {}
for i = 1, math.min(8, #rest) do top[i] = rest[i][1] .. " " .. rest[i][2] end
print("  most common classes without a layer: " .. table.concat(top, ", "))
